export function getTutorial(slug: string): Tutorial | undefined {
  return TUTORIALS.find(t => t.slug === slug);
}

export function getRelated(slug: string, limit = 3): Tutorial[] {
  const cur = getTutorial(slug);
  if (!cur) return [];
  return TUTORIALS
    .filter(t => t.slug !== slug && t.category === cur.category)
    .slice(0, limit);
}

export function getAdjacent(slug: string): { prev?: Tutorial; next?: Tutorial } {
  const i = TUTORIALS.findIndex(t => t.slug === slug);
  if (i === -1) return {};
  return {
    prev: i > 0 ? TUTORIALS[i - 1] : undefined,
    next: i < TUTORIALS.length - 1 ? TUTORIALS[i + 1] : undefined,
  };
}
